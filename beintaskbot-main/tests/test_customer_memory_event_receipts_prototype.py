    def test_overlapping_transactions_cannot_commit_sequence_out_of_scope_order(self):
        from tenant_platform import _connect
        a,b,version=(str(uuid.uuid4()) for _ in range(3))
        with _connect() as setup:
            with setup.cursor() as cur:self.pause(cur,False)
            setup.commit()
        started=threading.Event();finished=threading.Event();out=[];pids=[]
        def enqueue_second():
            try:
                with _connect() as conn:
                    with conn.cursor() as cur:
                        cur.execute("SET LOCAL lock_timeout='3s'")
                        cur.execute('SELECT pg_backend_pid() AS pid');pids.append(cur.fetchone()['pid'])
                        started.set();out.append(self.enqueue(cur,b,version))
                    conn.commit()
            except Exception as exc:out.append(type(exc).__name__)
            finally:finished.set()
        with _connect() as held:
            with held.cursor() as cur:
                first=self.enqueue(cur,a,version)
                cur.execute('SELECT pg_backend_pid() AS pid');holder=cur.fetchone()['pid']
                thread=threading.Thread(target=enqueue_second);thread.start()
                self.addCleanup(thread.join,4)
                self.assertTrue(started.wait(2));self.assert_blocked_by(pids[0],holder,finished)
            held.commit()
        thread.join(3);self.assertTrue(finished.is_set());self.assertGreater(out[0],first)
        with _connect() as conn:
            with conn.cursor() as cur:
                batch=self.claim(cur);self.assertEqual([str(x['source_id']) for x in batch['events']],[a,b])
            conn.commit()

