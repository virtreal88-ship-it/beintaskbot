const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('../.support-test-deps/node_modules/jsdom');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'docs/tenant-app.html'),'utf8');
const script=fs.readFileSync(path.join(root,'docs/tenant-workspace.js'),'utf8');
const settle=async()=>{for(let i=0;i<10;i++)await new Promise(resolve=>setImmediate(resolve));};

(async()=>{
 const dom=new JSDOM(html,{url:'https://crm.test/app?view=settings',runScripts:'outside-only'}),w=dom.window,d=w.document;
 w.tenantI18n={language:'ru'};w.tenantCanAccessCompanySettings=()=>true;
 w.HTMLElement.prototype.scrollIntoView=function(){};w.requestAnimationFrame=callback=>callback();
 w.tenantAppNavigate=(view)=>{d.querySelectorAll('.view').forEach(node=>node.classList.toggle('active',node.id==='view-'+(view==='settings'?'profile':view)));return true};
 d.querySelectorAll('.view').forEach(node=>node.classList.toggle('active',node.id==='view-profile'));
 w.eval(script);await settle();
 const profile=d.getElementById('view-profile'),general=d.getElementById('profile-company-settings'),tabs=general.querySelector('.settings-sections');
 const notificationRoot=d.getElementById('chakra-notification-settings-root');
 assert.ok(notificationRoot,'notification preferences keep their existing root');
 assert.equal(notificationRoot.parentElement,general,'notification UI moves into Profile without copying');
 notificationRoot.innerHTML='<article class="panel"><h2>Bildirişlər</h2></article>';
 assert.equal(d.getElementById('chakra-settings-root').parentElement.id,'profile-account-settings','account fields move into Profile');
 assert.ok(tabs,'profile general sections are initialized');
 assert.equal(tabs.parentElement,general,'general settings subsections belong to Profile');
 assert.equal(tabs.previousElementSibling.classList.contains('advanced-settings-title'),true);
 assert.equal(d.querySelector('[data-settings-page=settings]'),null,'Settings has no General tab');
 assert.equal(d.querySelector('.settings-family').hidden,true,'Settings tabs stay out of the profile');
 const workflow=d.createElement('article');workflow.id='workflowPanel';workflow.className='panel';general.append(workflow);
 const advanced=d.createElement('article');advanced.className='panel';general.append(advanced);
 await settle();
 assert.deepEqual([...tabs.querySelectorAll('[role=tab]')].map(button=>button.textContent),['Уведомления','Компании','Правила работы','Диагностика']);
 assert.equal([...tabs.querySelectorAll('[role=tab]')].filter(button=>!button.hidden).length,4);
 const notificationTab=tabs.querySelector('[data-settings-tab=notifications]');notificationTab.click();
 assert.equal(notificationRoot.hidden,false,'notification preferences remain available from Profile');
 assert.match(notificationRoot.textContent,/Bildirişlər/);
 tabs.querySelector('[data-settings-tab=advanced]').click();assert.equal(notificationRoot.hidden,true);
 let integrationsOpened=0;d.querySelector('.nav [data-view="integrations"]').addEventListener('click',()=>integrationsOpened++);
 w.tenantOpenSettingsSection('notifications');await settle();
 assert.equal(integrationsOpened,0,'personal notification preferences do not navigate to Integrations');
 assert.equal(notificationRoot.hidden,false);assert.equal(notificationTab.getAttribute('aria-selected'),'true');
 w.tenantI18n.language='az';d.dispatchEvent(new w.CustomEvent('tenant-language',{detail:{language:'az'}}));
 assert.deepEqual([...tabs.querySelectorAll('[role=tab]')].map(button=>button.textContent),['Bildirişlər','Şirkətlər','İş qaydaları','Diaqnostika']);
 w.tenantI18n.language='en';d.dispatchEvent(new w.CustomEvent('tenant-language',{detail:{language:'en'}}));
 assert.deepEqual([...tabs.querySelectorAll('[role=tab]')].map(button=>button.textContent),['Notifications','Companies','Work rules','Diagnostics']);
 assert.equal(profile.querySelector('#profile-company-settings'),general);
 dom.window.close();console.log('PASS: profile fields and preserved general settings relocalize RU/AZ/EN.');
})().catch(error=>{console.error(error);process.exitCode=1});
